def main() -> None:
    fields = (
        "id",
        "subject",
        "body",
        "requester",
        "company",
        "project",
        "priority",
        "status",
        "assignee",
        "created_at",
        "updated_at",
    )
    relay = {
        "projects": PROJECTS,
        "users": USERS,
        "tickets": [dict(zip(fields, t, strict=True)) for t in TICKETS],
        "comments": COMMENTS,
    }
    post = {"messages": sorted(MESSAGES, key=lambda m: m["id"])}
    assert len({m["id"] for m in MESSAGES}) == len(MESSAGES)
    for rel, data in (
        ("environment/relaydesk/seed.json", relay),
        ("tests/seed-relaydesk.json", relay),
        ("environment/postbox/seed.json", post),
        ("tests/seed-postbox.json", post),
    ):
        out = TASK / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
        print(f"wrote {out.relative_to(TASK.parent)}")


if __name__ == "__main__":
    main()
